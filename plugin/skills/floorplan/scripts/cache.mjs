// Per-file cache of parse results, keyed by file size + modification time.
// Unchanged files are not read again, so maps of big repositories (and the per-edit hook) stay fast.
// Lives in the local folder (.floorplan/), which is never committed. Delete it any time; it is rebuilt.
import fs from 'node:fs';
import path from 'node:path';

export function openCache(dir, name, version) {
  const file = path.join(dir, `cache-${name}.json`);
  let data = { version, files: {} };
  try {
    const d = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (d.version === version) data = d;
  } catch { /* no cache yet */ }
  const used = new Set();
  let dirty = false;
  const stamp = (abs) => { try { const s = fs.statSync(abs); return `${s.size}:${Math.floor(s.mtimeMs)}`; } catch { return null; } };
  return {
    // facts for this file if it didn't change, else undefined
    get(abs) {
      const e = data.files[abs];
      if (!e) return undefined;
      if (e.stamp !== stamp(abs)) return undefined;
      used.add(abs);
      return e.facts;
    },
    set(abs, facts) { data.files[abs] = { stamp: stamp(abs), facts }; used.add(abs); dirty = true; },
    save() {
      for (const k of Object.keys(data.files)) if (!used.has(k)) { delete data.files[k]; dirty = true; }
      if (!dirty) return;
      try {
        fs.mkdirSync(dir, { recursive: true });
        const ignore = path.join(dir, '.gitignore');
        if (!fs.existsSync(ignore)) fs.writeFileSync(ignore, '# Generated by floorplan. Local only, never committed.\n*\n');
        fs.writeFileSync(file, JSON.stringify(data));
      } catch { /* read-only checkout: no cache */ }
    },
  };
}
