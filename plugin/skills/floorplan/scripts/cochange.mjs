#!/usr/bin/env node
// Files in different areas that change together in the same commits: a hint that one of them is in the wrong place
// (or that two areas are more coupled than the imports show). Reads git history; changes nothing.
//   node scripts/floorplan/cochange.mjs                 last 12 months, pairs seen in at least 4 commits
//   options: --since "6 months ago"  --min 4  --confidence 0.6  --max-files 30 (ignore bigger commits)  --top 30
//            --json (machine-readable)  --config <file>
// Writes .floorplan/COCHANGE.md as well.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { loadConfig, globToRegex, toPosix, defaultConfigPath } from './lib.mjs';

const args = process.argv.slice(2);
const val = (n, d) => (args.includes(n) ? args[args.indexOf(n) + 1] : d);
const config = await loadConfig(val('--config', defaultConfigPath()));
const since = val('--since', '12 months ago'), minSupport = Number(val('--min', 4)), minConf = Number(val('--confidence', 0.6));
const maxFiles = Number(val('--max-files', 30)), top = Number(val('--top', 30));
const repoRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
const rootRepo = toPosix(path.relative(repoRoot, path.resolve(config.root)));
const ext = config.framework === 'spring' ? /\.java$/ : /\.ts$/;
const skip = /\.(spec|test)\.ts$|Tests?\.java$|IT\.java$/;
const units = config.units && config.units.length ? config.units : null;
function unitOf(p) {
  for (const pat of units || []) {
    const m = globToRegex(pat).exec(p);
    if (m) { let i = 1; return pat.replace(/\*\*?/g, () => m[i++] ?? '*').replace(/\/\*\*$/, ''); }
  }
  return p.includes('/') ? p.split('/')[0] : '(root)';
}
const log = execFileSync('git', ['-C', repoRoot, 'log', `--since=${since}`, '--no-merges', '--name-only', '--format=@@%H', '--', rootRepo || '.'], { encoding: 'utf8', maxBuffer: 1 << 30 });
const commits = [];
let cur = null;
for (const line of log.split('\n')) {
  if (line.startsWith('@@')) { cur = []; commits.push(cur); continue; }
  if (!line || !cur) continue;
  const p = rootRepo ? (line.startsWith(rootRepo + '/') ? line.slice(rootRepo.length + 1) : null) : line;
  if (p && ext.test(p) && !skip.test(p) && fs.existsSync(path.join(repoRoot, line))) cur.push(p);
}
const count = new Map(), pair = new Map();
let used = 0;
for (const c of commits) {
  const fs_ = [...new Set(c)];
  if (fs_.length < 2 || fs_.length > maxFiles) continue;
  used++;
  for (const f of fs_) count.set(f, (count.get(f) || 0) + 1);
  for (let i = 0; i < fs_.length; i++) for (let j = i + 1; j < fs_.length; j++) {
    const [a, b] = [fs_[i], fs_[j]].sort();
    if (unitOf(a) === unitOf(b)) continue;
    const k = `${a}\0${b}`; pair.set(k, (pair.get(k) || 0) + 1);
  }
}
const rows = [];
for (const [k, n] of pair) {
  if (n < minSupport) continue;
  const [a, b] = k.split('\0');
  const confA = n / count.get(a), confB = n / count.get(b);
  const conf = Math.max(confA, confB);
  if (conf < minConf) continue;
  // the file that changes mostly together with the other one is the one that probably belongs there
  const [mover, partner] = confA >= confB ? [a, b] : [b, a];
  rows.push({ mover, partner, together: n, moverChanges: count.get(mover), confidence: Math.round(conf * 100) / 100, from: unitOf(mover), to: unitOf(partner) });
}
rows.sort((x, y) => y.confidence - x.confidence || y.together - x.together);
const shown = rows.slice(0, top);
if (args.includes('--json')) { console.log(JSON.stringify({ since, commits: used, pairs: rows }, null, 2)); process.exit(0); }
const L = ['# Change coupling between areas', '', `> Generated by \`scripts/floorplan/cochange.mjs\` from git history since ${since} (${used} commits with 2–${maxFiles} source files). Local only.`, '',
  `Pairs of files in different areas that changed together in at least ${minSupport} commits, where at least ${Math.round(minConf * 100)}% of one file's changes came with the other.`,
  'The first file is the one that usually moves along: it may belong in the other area (or the two areas share a concept that wants its own place).', ''];
if (!shown.length) L.push('No strongly coupled pairs found.');
else {
  L.push('| File | changes with | Together | Of its changes | Areas |', '|---|---|---|---|---|');
  for (const r of shown) L.push(`| ${r.mover} | ${r.partner} | ${r.together} | ${Math.round(r.confidence * 100)}% | ${r.from} → ${r.to} |`);
}
const md = L.join('\n') + '\n';
const local = path.resolve(config.output?.local || '.floorplan');
fs.mkdirSync(local, { recursive: true });
if (!fs.existsSync(path.join(local, '.gitignore'))) fs.writeFileSync(path.join(local, '.gitignore'), '*\n');
fs.writeFileSync(path.join(local, 'COCHANGE.md'), md);
console.log(md);
console.log(`(also written to ${toPosix(path.relative(process.cwd(), local))}/COCHANGE.md)`);
