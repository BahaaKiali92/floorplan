#!/usr/bin/env node
// Adds or updates the "Project structure" section in CLAUDE.md. Run it again after changing the config or updating
// the tools: it replaces its own section and never touches the rest of the file.
//
//   node scripts/floorplan/claude-md.mjs              # uses framework, output path and `ci` from floorplan.config.mjs
//   node scripts/floorplan/claude-md.mjs --no-ci      # no CI job regenerates the main map (someone runs --main on main)
//   node scripts/floorplan/claude-md.mjs --print      # only print the section
//   options: --file <CLAUDE.md>, --config <file>
//
// Keeps the file's line endings (CRLF on Windows) and byte order mark. Recognizes the section written by older
// versions (a "## Project structure" heading with an @…FLOORPLAN.md reference) and replaces it.
import fs from 'node:fs';
import path from 'node:path';
import { loadConfig, defaultConfigPath } from './lib.mjs';

const args = process.argv.slice(2);
const val = (n) => (args.includes(n) ? args[args.indexOf(n) + 1] : undefined);
const config = await loadConfig(val('--config') || defaultConfigPath());
const ci = args.includes('--no-ci') ? false : args.includes('--ci') ? true : config.ci !== false;
const spring = config.framework === 'spring';
const mapPath = (config.output.markdown || 'docs/FLOORPLAN.md').replace(/\\/g, '/');
const S = 'node scripts/floorplan/generate-map.mjs';
const cmd = spring
  ? { map: S, check: `${S} --check`, main: `${S} --main` }
  : { map: 'npm run map', check: 'npm run map:check', main: 'npm run map:main' };

const L = [];
L.push('<!-- floorplan:start (generated by scripts/floorplan/claude-md.mjs; edit the config, not this section) -->');
L.push('## Project structure', '');
L.push(ci
  ? 'Structure of the main branch (regenerated by CI after every merge to main; never edit it by hand):'
  : `Structure of the main branch (there is no CI job for it: after merging to main, someone runs \`${cmd.main}\` on main and commits it; never edit it by hand):`);
L.push('', `@${mapPath}`, '');
L.push('In big repositories this file is an overview: before working in an area, read its detail file (linked in the Areas table).', '');
L.push(`What the current branch changed compared with main is in \`${config.output.local || '.floorplan'}/BRANCH_CHANGES.md\` (local, never committed).`);
L.push(`A short summary of it is added automatically at the start of every session. Refresh it with \`${cmd.map}\`.`, '');
if (spring) {
  L.push('- Before creating a class, find the right package in the map and follow the package purposes and rules there.');
  L.push('- Before changing a controller or service, check "Dependencies between areas" and "HTTP endpoints and listeners".');
  L.push('- Move classes and packages with `node scripts/floorplan/move-cli.mjs <source> <target-folder>` (dry run, paths');
  L.push('  relative to the map root), then add `--apply`. It changes package declarations, rewrites every import (also for');
  L.push('  classes that were in the same package), moves the matching tests and refreshes the local map. Read its warnings:');
  L.push('  strings, `application.yml` and XML are not rewritten.');
} else {
  L.push('- Before creating a file, find the right folder in the map and follow the folder purposes and rules there.');
  L.push('- Before changing a component or service, check "Dependencies between areas" to see what else could be affected.');
  L.push('- Move files and folders with `node scripts/floorplan/move-cli.mjs <source> <target-folder>` (dry run), then add `--apply`.');
  L.push('  It moves companions (.html, .scss, .spec.ts), rewrites every import and refreshes the local map.');
}
L.push('- If a hook reports that a file you wrote breaks a rule, fix it right away (`node scripts/floorplan/move-cli.mjs <file> --fix` suggests the folder).');
L.push(`- After creating, moving or deleting files, run \`${cmd.map}\` (local map and branch report only).`);
L.push(ci
  ? `- Do not run \`${cmd.main}\` and do not edit \`${mapPath}\`: CI regenerates it after merges to main.`
  : `- Run \`${cmd.main}\` only on main, after a merge, and commit the result. On a branch, never; and never edit \`${mapPath}\` by hand.`);
L.push(`- Before finishing a task, run your normal checks (${spring ? 'compile, tests' : 'type check, tests, lint'}) as usual, and **in addition**`);
L.push(`  \`${cmd.check}\`, which must pass. It fails only on rule issues this branch introduced. Fix them by moving the`);
L.push('  file or changing the import; do not change a rule unless asked.');
L.push('- The rules written in this CLAUDE.md are checked too (`floorplan.claude-rules.json`, as warnings). When you change');
L.push('  the rules in this file, run `/floorplan rules` so the checks follow; the map says when they are out of date.');
L.push('<!-- floorplan:end -->');
const section = L.join('\n');

if (args.includes('--print')) { console.log(section); process.exit(0); }

const file = path.resolve(val('--file') || 'CLAUDE.md');
let text = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
const bom = text.startsWith('﻿') ? '﻿' : '';
if (bom) text = text.slice(1);
const eol = /\r\n/.test(text) ? '\r\n' : '\n';
const lf = text.replace(/\r\n/g, '\n');
let next, action;
const marked = /<!-- (?:floorplan|project-map):start[\s\S]*?<!-- (?:floorplan|project-map):end -->/; // also the section from before the rename
if (marked.test(lf)) { next = lf.replace(marked, section); action = 'updated'; }
else {
  // older versions: "## Project structure" … up to the next "## " heading (or the end), if it references a FLOORPLAN.md
  const old = /(^|\n)## Project structure\n[\s\S]*?(?=\n## |\n# |$)/;
  const m = old.exec(lf);
  if (m && /@[^\s]*(PROJECT_MAP|FLOORPLAN)\.md/.test(m[0])) { next = lf.replace(old, (all, pre) => `${pre}${section}`); action = 'replaced the older section in'; }
  else { next = (lf.trimEnd() ? lf.trimEnd() + '\n\n' : '') + section + '\n'; action = fs.existsSync(file) ? 'appended to' : 'created'; }
}
const out = bom + next.replace(/\n/g, eol);
if (out === (bom + text)) { console.log(`✓ ${path.basename(file)} is up to date.`); process.exit(0); }
fs.writeFileSync(file, out);
console.log(`✓ Project structure section ${action} ${path.relative(process.cwd(), file) || file}${eol === '\r\n' ? ' (CRLF kept)' : ''}${ci ? '' : ' (no-CI wording)'}.`);
